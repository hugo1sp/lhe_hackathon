"""Bake forecast accuracy vs. manual inputs into app/accuracy_data.js for the app's live mode.

Uses the team's evaluation in model/personal.py (walk-forward, person-grouped, scored on true
attacks on every day) and reports ROC AUC:
  - by month of app use: watch-only base vs. base + the user's one-tap answers (personal layer)
  - by answers per week: same users with a random share of their answers kept

Needs data/ from the pipeline (simulator, collection/simulate_answers.py, model/base.py).

Usage: .venv/bin/python app/build_accuracy.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "model"))
import personal as pm  # noqa: E402

LAM = 30.0  # same default as model/personal.py

data = ROOT / "data"
daily = pd.read_csv(data / "daily.csv", parse_dates=["date"])
labels = pd.read_csv(data / "labels.csv", parse_dates=["date"])
base = pd.read_csv(data / "base_oof.csv", parse_dates=["date"])
auc = pm.roc_auc_score

X, meta = pm.build(daily, labels, base)
_, p_per, _ = pm.evaluate(X, meta, LAM)
meta = meta.assign(p_per=p_per, y=meta["y_true"].astype(int), month=meta["day"] // 30)
by_month = [{"month": int(m), "n": len(g), "base": round(auc(g.y, g.p_base), 3), "answers": round(auc(g.y, g.p_per), 3)}
            for m, g in meta.groupby("month")]

rng = np.random.default_rng(0)  # same draw as model/personal.py
n_days = daily.groupby("person_id").size().mean()
by_rate = []
for keep in [0.0, 0.25, 0.5, 1.0]:
    kept = labels[rng.random(len(labels)) < keep]
    Xk, mk = pm.build(daily, kept, base)
    _, pk, _ = pm.evaluate(Xk, mk, LAM)
    by_rate.append({"per_week": round(7 * len(kept) / daily["person_id"].nunique() / n_days, 1),
                    "auc": round(auc(mk["y_true"].astype(int), pk), 3)})

out = {"users": int(meta["person_id"].nunique()), "by_month": by_month, "by_rate": by_rate}
(ROOT / "app/accuracy_data.js").write_text(
    "// Forecast accuracy (ROC AUC) vs. manual inputs. Generated by app/build_accuracy.py - do not edit by hand.\n"
    "// Source: model/personal.py evaluation on the simulator data (walk-forward, scored on true attacks).\n"
    f"const ACCURACY = {json.dumps(out)};\n")
print(json.dumps(out, indent=1))
