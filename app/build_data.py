"""Bake Anna's (simulated person P0187) data into app/anna_data.js for the app.

Sources (data/ is gitignored, so the output is committed as a static file):
  data/daily.csv, data/persons.csv  - simulator output, 2026-01-01 .. 2026-06-25
  mockup/demo_data.js               - model forecast `risk` per day (made the evening before), 2026-05-14 .. 06-24
  demo/anna_data.js                 - forecast made on 2026-06-24 evening: p1/p2/p3 for 06-25/26/27
Question policy: collection/questions.py, run on the forecast risk.

The `app` section (times of day, intensity, medication, which questions were answered)
is illustrative app-side detail, invented with a fixed seed - not simulator output.

Usage: .venv/bin/python app/build_data.py
"""

import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "collection"))
from questions import pick_questions  # noqa: E402

PID, END = "P0187", "2026-06-25"


def js_const(path, name):
    text = (ROOT / path).read_text()
    return json.loads(re.search(rf"const {name} = (\{{.*\}});", text, re.S).group(1))


daily = pd.read_csv(ROOT / "data/daily.csv")
d = daily[(daily.person_id == PID) & (daily.date <= END)].reset_index(drop=True)
p = pd.read_csv(ROOT / "data/persons.csv").set_index("person_id").loc[PID]
demo, anna = js_const("mockup/demo_data.js", "DEMO"), js_const("demo/anna_data.js", "ANNA")

# Forecast risk per day (made the evening before); NaN where no forecast exists.
risk = {r["date"]: r["risk"] for r in demo["days"]}
f = anna["forecast_0624"]
risk[f["date"][:8] + "25"] = f["p1"]  # forecast for 06-25 made on 06-24 evening
d["risk"] = d.date.map(risk)

# Personal baselines: mean of the previous 14 days (same definition as demo/anna_data.js).
cols = {"sleep_hours": "sleep", "sleep_efficiency": "eff", "sleep_midpoint_h": "mid", "resting_hr": "rhr",
        "hrv_rmssd": "hrv", "steps": "steps", "stress_score": "stress"}
for c in cols:
    d["base_" + c] = d[c].shift(1).rolling(14, min_periods=5).mean()

# Question the app asked each day (team policy, driven by the forecast, not ground truth).
qs = pick_questions(d, d["risk"].to_numpy())

# Illustrative app-side details (invented, seeded).
rng = np.random.default_rng(187)


def answer(q, i):
    mig = d.migraine.iat[i] == 1
    nxt = d.migraine.iloc[i + 1:i + 3].sum() > 0
    if q["id"] == "attack_check":
        return ["Mild", "Moderate", "Severe"][rng.integers(0, 3)] if mig else "No"
    if q["id"] == "prodrome":
        return "A little" if nxt else "No"
    if q["id"] == "anomaly":
        return "Headache" if mig else "Stress" if d.stress_score.iat[i] > 70 else "Nothing"
    return "Yes" if mig else "No"


days = []
for i, r in d.iterrows():
    row = {"date": r.date, "cd": None if pd.isna(r.cycle_day) else int(r.cycle_day), "mig": int(r.migraine)}
    for c, k in cols.items():
        row[k] = None if pd.isna(r[c]) else round(float(r[c]), 3 if k == "eff" else 2)
        b = r["base_" + c]
        row["b_" + k] = None if pd.isna(b) else round(float(b), 3 if k == "eff" else 2)
    row["risk"] = None if pd.isna(r.risk) else round(float(r.risk), 3)
    q = qs[i]
    if r.migraine:
        hour = int(rng.choice([7, 9, 11, 13, 14, 15, 16, 18]))
        row["log"] = {"t": f"{hour:02d}:{int(rng.integers(0, 12)) * 5:02d}",
                      "int": ["Mild", "Moderate", "Severe"][int(rng.choice(3, p=[.3, .5, .2]))],
                      "meds": [["Triptan"], ["Ibuprofen"], ["Triptan", "Ibuprofen"], ["Paracetamol"]][int(rng.integers(0, 4))],
                      "src": "watch" if q and q["id"] == "attack_check" else "tap"}
    if q:
        row["q"] = q["id"] + (":" + q["signal"] if "signal" in q else "")
        row["a"] = answer(q, i) if rng.random() < 0.85 else None
        if row["a"] and q["id"] == "attack_check" and r.migraine:
            row["a"] = row["log"]["int"]  # the confirmed attack carries the chosen intensity
    days.append(row)

# The 06-25 attack matches the narrated demo: confirmed on the watch at 14:10, details not yet added.
days[-1]["log"] = {"t": "14:10", "int": None, "meds": [], "src": "watch"}

out = {
    "person": {"id": PID, "name": "Anna", "age": int(p.age), "cycle_length": int(p.cycle_length),
               "triggers": {"sleep_debt": round(p.sens_sleep_debt, 2), "sleep_irregularity": round(p.sens_sleep_irregularity, 2),
                            "stress": round(p.sens_stress, 2), "menstrual": round(p.sens_menstrual, 2)}},
    "outlook": {"made": "2026-06-24", "2026-06-25": f["p1"], "2026-06-26": f["p2"], "2026-06-27": f["p3"]},
    "days": days,
}
header = (
    "// Simulated person P0187 (\"Anna\", 23). Generated by app/build_data.py - do not edit by hand.\n"
    "// Physiology + reported migraines: data/daily.csv, data/persons.csv (simulator, 2026-01-01..06-25).\n"
    "// risk = model forecast for that day, made the evening before (mockup/demo_data.js; 06-25 from demo/anna_data.js).\n"
    "// outlook = 3-day forecast made on 06-24 evening. b_* = mean of the previous 14 days.\n"
    "// q = question asked that day (collection/questions.py policy on the forecast). a, log.t/int/meds/src are\n"
    "// illustrative app-side details (invented, seeded), not simulator output.\n"
)
(ROOT / "app/anna_data.js").write_text(header + "const ANNA = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(f"wrote app/anna_data.js: {len(days)} days, {d.migraine.sum()} logged migraines, {d.risk.notna().sum()} forecasts")
