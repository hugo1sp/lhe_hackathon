"""Export the actual watch, model forecasts and question policy for Anna's product demo."""
import hashlib
import json
import sys
from pathlib import Path

import lightgbm as lgb
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / name) for name in ("simulator", "collection", "model")]
from base import HORIZONS, build_features, p_col, predict_base, with_dow
from questions import pick_questions, render
from simulate import ANNA, simulate
from simulate_answers import answer

DEFAULT_INDEX = 170  # June 20: a fixed starting date with almost six months of example history.
COLS = {"sleep_hours": "sleep", "sleep_efficiency": "eff", "sleep_midpoint_h": "mid",
        "resting_hr": "rhr", "hrv_rmssd": "hrv", "steps": "steps", "stress_score": "stress"}


def number(value):
    return None if pd.isna(value) else round(float(value), 6)


def build_source():
    watch, truth = simulate(365, "2026-01-01", seed=0)
    dated = watch.assign(date=lambda d: pd.to_datetime(d.date))
    forecasts = predict_base(dated, ROOT / "data")
    by_date = forecasts.set_index("date")
    risk = by_date.p_base.reindex(pd.to_datetime(watch.date) - pd.Timedelta(days=1)).to_numpy()
    questions = pick_questions(watch, risk)
    baselines = watch[list(COLS)].shift(1).rolling(28, min_periods=7).mean()
    X, meta = build_features(dated)
    model = lgb.Booster(model_file=str(ROOT / "data/model_base_d1.txt"))
    contributions = model.predict(with_dow(X, meta, 1), pred_contrib=True)
    effect_by_date = {}
    for date, values in zip(meta.date, contributions):
        effects = {}
        for feature, value in zip(list(X.columns) + ["dow_ahead"], values[:-1]):
            key = next((short for col, short in COLS.items() if feature.startswith(col)), None)
            if feature == "sleep_midpoint_irreg": key = "mid"
            if key == "eff": key = "sleep"
            if key: effects[key] = effects.get(key, 0.0) + float(value)
        effect_by_date[date] = {k: number(v) for k, v in effects.items()}

    days = []
    for i, w in watch.iterrows():
        date = pd.Timestamp(w.date)
        row = {"date": w.date, "cd": None, "mig": int(truth.true_migraine.iat[i]),
               "risk": number(risk[i]), "effects": effect_by_date.get(date, {}), "forecast": []}
        for col, short in COLS.items():
            row[short] = number(w[col])
            row["b_" + short] = number(baselines[col].iat[i])
        if date in by_date.index:
            f = by_date.loc[date]
            row["forecast"] = [{"date": str((date + pd.Timedelta(days=h)).date()),
                                "p": number(f[p_col(h)])} for h in HORIZONS]
        if questions[i]:
            row["policy"] = render(questions[i])
            row["q"] = questions[i]["id"] + (":" + questions[i]["signal"] if "signal" in questions[i] else "")
        # Historical example records only. New days require the viewer's own input.
        if i < DEFAULT_INDEX:
            if row["mig"]:
                row["log"] = {"t": "time unknown", "int": None, "meds": [], "src": "example"}
            if questions[i]:
                person = pd.Series({"true_migraine": row["mig"], "intensity": 3,
                                    "prodrome": int(truth.true_prodrome.iat[i] > 0), "true_illness": 0,
                                    "stress_score": w.stress_score})
                row["a"] = answer(questions[i]["id"], person, None)
        days.append(row)
    return {"followup": render({"id": "checkin"}), "defaultIndex": DEFAULT_INDEX, "person": {"id": ANNA["person_id"], "name": "Anna", "age": 23,
            "cycle_length": None, "triggers": {"sleep_debt": 1, "sleep_irregularity": 1, "stress": 1}},
            "models": [{"file": f"data/model_base_d{h}.txt", "sha256": hashlib.sha256(
                (ROOT / f"data/model_base_d{h}.txt").read_bytes()).hexdigest()} for h in HORIZONS], "days": days}


if __name__ == "__main__":
    source = build_source()
    path = Path(__file__).with_name("anna_data.js")
    path.write_text("// Generated by demo_model/build_data.py using the project's saved LightGBM models.\n"
                    "window.MODEL_LIVE = false;\nconst ANNA_SOURCE = " + json.dumps(source, separators=(",", ":"), allow_nan=False) + ";\n")
    print(f"Wrote {len(source['days'])} days of actual model outputs to {path}")
